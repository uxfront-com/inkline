/**
 * Generates `src/recipes.ts`: the props type of each Styleframe recipe the components use, like
 * `ButtonRecipeProps`. A component types its recipe props from this module, since Unframework
 * passes `virtual:styleframe` through only for the recipe functions a `class` calls (UF5006), not
 * for its types.
 *
 * It loads `styleframe.config.ts` and every `*.styleframe.ts` file under `src/` the way Styleframe's
 * Vite plugin does, and keeps the `…RecipeProps` types of the declarations Styleframe's transpiler
 * writes for `virtual:styleframe`. `scripts/recipes.test.ts` fails when the committed file differs.
 * `scripts/styleframe-types.ts` writes those declarations to `.styleframe/` from the same loading.
 *
 * Run it with `node scripts/recipes.ts` from `ui/components` to write the file again.
 */
import { mkdtempSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, relative, resolve } from "node:path";

import { createSharedJiti, loadExtensionModule, loadModule } from "@styleframe/loader";
import { DTS_TYPES_FILENAME, transpile } from "@styleframe/transpiler";

export const ROOT = resolve(import.meta.dirname, "..");
export const RECIPES_FILE = join(ROOT, "src/recipes.ts");

/** The key Styleframe's plugin keeps the configuration's instance under while an extension loads. */
const GLOBAL_INSTANCE_KEY = "__STYLEFRAME_GLOBAL_INSTANCE__";

const HEADER = `// Generated by \`scripts/recipes.ts\` from the \`*.styleframe.ts\` files: don't edit it by hand.
// Run \`node scripts/recipes.ts\` to write it again. \`scripts/recipes.test.ts\` fails when it's stale.
`;

/** The `*.styleframe.ts` files under `src/`, in path order. */
function styleframeFiles(dir = join(ROOT, "src")): Array<string> {
	return readdirSync(dir, { withFileTypes: true, recursive: true })
		.filter((entry) => entry.isFile() && entry.name.endsWith(".styleframe.ts"))
		.map((entry) => join(entry.parentPath, entry.name))
		.sort();
}

/**
 * The type declarations Styleframe's transpiler writes for the components' configuration and
 * recipes, as `{ name, content }` files: the ones Styleframe's Vite plugin writes to `.styleframe/`.
 */
export async function transpileTypes(): Promise<Array<{ name: string; content: string }>> {
	// Each extension imports `styleframe()` from `virtual:styleframe`, which returns the instance the
	// configuration created. Styleframe's plugin serves it from a shim of its own, as here.
	const shimDir = mkdtempSync(join(tmpdir(), "inkline-recipes-"));
	const shim = join(shimDir, "shim.mjs");
	writeFileSync(
		shim,
		`export function styleframe() { return globalThis[${JSON.stringify(GLOBAL_INSTANCE_KEY)}]; }\n`,
	);
	try {
		const jiti = createSharedJiti({ alias: { "virtual:styleframe": shim } });
		const { instance } = await loadModule(join(ROOT, "styleframe.config.ts"), { jiti });
		const globals = globalThis as Record<string, unknown>;
		globals[GLOBAL_INSTANCE_KEY] = instance;
		try {
			for (const file of styleframeFiles()) {
				await loadExtensionModule(file, { alias: { "virtual:styleframe": shim }, jiti });
			}
		} finally {
			delete globals[GLOBAL_INSTANCE_KEY];
		}
		const { files } = await transpile(instance, { type: "dts" });
		return files;
	} finally {
		rmSync(shimDir, { recursive: true, force: true });
	}
}

/** The contents `src/recipes.ts` should have. */
export async function generateRecipes(): Promise<string> {
	const files = await transpileTypes();
	const types = files.find((file) => file.name === DTS_TYPES_FILENAME)?.content;
	if (!types) {
		throw new Error(`Styleframe's transpiler wrote no ${DTS_TYPES_FILENAME}`);
	}
	const declarations = [...types.matchAll(/^export type (\w+RecipeProps) = (.+);$/gm)]
		.map(([, name, type]) => `export type ${name} = ${type};\n`)
		.sort();
	if (declarations.length === 0) {
		throw new Error("Styleframe declared no recipe props");
	}
	return `${HEADER}\n${declarations.join("")}`;
}

if (process.argv[1] && resolve(process.argv[1]) === import.meta.filename) {
	writeFileSync(RECIPES_FILE, await generateRecipes());
	console.log(`Wrote ${relative(process.cwd(), RECIPES_FILE)}`);
}
